Map::TileMapMbtilesWriter::TileMapMbtilesWriter(Text::CStringNN fileName, Map::TileMap::TileFormat format, UIntOS minLev, UIntOS maxLev, Math::RectAreaDbl bounds)
{
	NEW_CLASSNN(this->db, DB::SQLiteFile(fileName));
	this->sess = nullptr;
	this->imgCount = 0;
	if (!this->db->IsError())
	{
		this->db->ExecuteNonQuery(CSTR("CREATE TABLE IF NOT EXISTS metadata (name TEXT, value TEXT, PRIMARY KEY (name))"));
		this->db->ExecuteNonQuery(CSTR("CREATE TABLE IF NOT EXISTS tiles (zoom_level INTEGER, tile_column INTEGER, tile_row INTEGER, tile_data BLOB, PRIMARY KEY (zoom_level, tile_column, tile_row))"));
		this->db->ExecuteNonQuery(CSTR("DELETE FROM metadata"));
		this->db->ExecuteNonQuery(CSTR("DELETE FROM tiles"));

		UIntOS i = fileName.LastIndexOf(IO::Path::PATH_SEPERATOR);
		UIntOS j = fileName.LastIndexOf('.', i + 1);
		NN<Text::String> name;
		if (j == INVALID_INDEX)
		{
			name = Text::String::New(fileName.Substring(i + 1));
		}
		else
		{
			name = Text::String::New(fileName.v + i + 1, j - i - 1);
		}

		this->AddMetadata(CSTR("name"), name->ToCString());
		name->Release();
		this->AddMetadata(CSTR("version"), CSTR("1.3"));
		this->AddMetadata(CSTR("description"), CSTR(""));
		this->AddMetadata(CSTR("attribution"), CSTR("Generated by AVIRead (sswroom)"));
		this->AddMetadata(CSTR("type"), CSTR("overlay"));
		switch (format)
		{
		case Map::TileMap::TileFormat::WEBP:
			this->AddMetadata(CSTR("format"), CSTR("webp"));
			break;
		case Map::TileMap::TileFormat::JPG:
			this->AddMetadata(CSTR("format"), CSTR("jpg"));
			break;
		case Map::TileMap::TileFormat::PNG:
			this->AddMetadata(CSTR("format"), CSTR("png"));
			break;
		}

		UTF8Char sbuff[64];
		UnsafeArray<UTF8Char> sptr = Text::StrUIntOS(sbuff, minLev);
		this->AddMetadata(CSTR("minzoom"), CSTRP(sbuff, sptr));
		sptr = Text::StrUIntOS(sbuff, maxLev);
		this->AddMetadata(CSTR("maxzoom"), CSTRP(sbuff, sptr));

		Text::StringBuilderUTF8 boundsStr;
		boundsStr.AppendDouble(bounds.min.x);
		boundsStr.AppendC(UTF8STRC(","));
		boundsStr.AppendDouble(bounds.min.y);
		boundsStr.AppendC(UTF8STRC(","));
		boundsStr.AppendDouble(bounds.max.x);
		boundsStr.AppendC(UTF8STRC(","));
		boundsStr.AppendDouble(bounds.max.y);
		this->AddMetadata(CSTR("bounds"), boundsStr.ToCString());
		this->AddMetadata(CSTR("profile"), CSTR("mercator"));

		this->sess = this->db->BeginTransaction();
	}
}

Map::TileMapMbtilesWriter::~TileMapMbtilesWriter()
{
	NN<DB::DBTransaction> sess;
	if (this->sess.SetTo(sess))
	{
		this->db->Commit(sess);
		this->sess = nullptr;
	}
	this->db.Delete();
}

void Map::TileMapMbtilesWriter::AddMetadata(Text::CStringNN key, Text::CStringNN value)
{
	DB::SQLBuilder sql(this->db->GetSQLType(), this->db->IsAxisAware(), this->db->GetTzQhr());
	sql.AppendCmdC(CSTR("INSERT INTO metadata (name, value) VALUES ("));
	sql.AppendStrC(key);
	sql.AppendCmdC(CSTR(", "));
	sql.AppendStrC(value);
	sql.AppendCmdC(CSTR(")"));
	this->db->ExecuteNonQuery(sql.ToCString());
}

